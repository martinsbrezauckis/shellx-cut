#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const manualScriptPath = `${root}docs/public/site/manual/manual.js`
const manualIndexPath = `${root}docs/public/site/manual/cut/index.html`
const packagePath = `${root}ui/package.json`
const outputPath = `${root}ui/src/manual/content.generated.json`
const readOnlyOutputPath = `${root}ui/src/manual/readOnlyVerbs.generated.ts`
const schemaPath = `${root}schema/verbs.json`

function groupFor(id) {
  const [, group = 'other'] = id.split('.')
  return group
}

function evaluateManualRegistry(source) {
  const end = source.indexOf('\nfunction updateHighlight(')
  if (end < 0) throw new Error('manual.js registry boundary was not found')
  const registrySource = source.slice(0, end)
  return Function(`"use strict";\n${registrySource}\nreturn { features, legacyFeatureAliases };`)()
}

function indexedFeatures(html) {
  const ids = []
  for (const match of html.matchAll(/<button\b[^>]*\bdata-feature-id="([^"]+)"[^>]*>([\s\S]*?)<\/button>/g)) {
    ids.push({
      id: match[1],
      label: match[2].replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim(),
    })
  }
  return ids
}

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`
}

async function writeOrCheck(path, content, check) {
  if (!check) {
    await writeFile(path, content)
    return
  }
  const current = await readFile(path, 'utf8').catch(() => '')
  if (current !== content) throw new Error(`${path} is stale; run node scripts/generate-manual-content.mjs`)
}

const check = process.argv.includes('--check')
const [manualScript, manualIndex, packageJson, schemaJson] = await Promise.all([
  readFile(manualScriptPath, 'utf8'),
  readFile(manualIndexPath, 'utf8'),
  readFile(packagePath, 'utf8'),
  readFile(schemaPath, 'utf8'),
])
const { features, legacyFeatureAliases } = evaluateManualRegistry(manualScript)
const indexed = indexedFeatures(manualIndex)
const seen = new Set()
const content = indexed.map(({ id, label }) => {
  if (seen.has(id)) throw new Error(`duplicate manual index feature: ${id}`)
  seen.add(id)
  const entry = features[id]
  if (!entry) throw new Error(`manual index feature has no definition: ${id}`)
  return {
    id,
    label,
    group: groupFor(id),
    title: entry.title,
    where: entry.where,
    description: entry.description,
    requirement: entry.requirement,
    api: entry.api,
  }
})
const unindexed = Object.keys(features).filter((id) => !seen.has(id))
if (content.length !== 199) throw new Error(`expected 199 indexed manual features, found ${content.length}`)

const appVersion = JSON.parse(packageJson).version
const output = {
  schema: 'shellx-cut/manual-content@1',
  appVersion,
  featureCount: content.length,
  features: content,
  aliases: legacyFeatureAliases,
  unindexed,
}

const schema = JSON.parse(schemaJson)
const readOnlyVerbs = schema.verbs
  .filter((verb) => verb?.behavior?.mutation_class === 'read')
  .map((verb) => verb.name)
  .sort()
const readOnlySource = `// Generated by scripts/generate-manual-content.mjs. Do not edit.\n` +
  `export const MANUAL_READ_ONLY_VERBS = new Set<string>(${JSON.stringify(readOnlyVerbs, null, 2)})\n`

await Promise.all([
  writeOrCheck(outputPath, stableJson(output), check),
  writeOrCheck(readOnlyOutputPath, readOnlySource, check),
])

console.log(`${check ? 'checked' : 'generated'} ${content.length} manual features and ${readOnlyVerbs.length} read-only verbs`)
